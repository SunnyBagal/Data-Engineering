-- =============================================================================
-- 00_setup/schema.sql — Practice database schema (PostgreSQL 13+)
-- -----------------------------------------------------------------------------
-- Run:   psql -d sql_course -f 00_setup/schema.sql -f 00_setup/seed.sql
-- The script is idempotent: it drops and recreates everything, so you can use
-- it to RESET the database after experimenting.
-- =============================================================================

-- Drop in one statement; CASCADE also removes views/foreign keys that other
-- lessons may have created on top of these tables. IF EXISTS avoids an error
-- on the very first run when nothing exists yet.
DROP TABLE IF EXISTS logins, payments, order_items, orders, products,
                     categories, customers, employees, departments CASCADE;

-- -----------------------------------------------------------------------------
-- departments: one row per department of the company
-- -----------------------------------------------------------------------------
CREATE TABLE departments (
    -- GENERATED BY DEFAULT AS IDENTITY = auto-increment (SQL standard).
    -- Preferred over the old SERIAL type: it is standard SQL and permissions
    -- on the hidden sequence are handled automatically. "BY DEFAULT" (instead
    -- of "ALWAYS") lets the seed file insert explicit ids.
    dept_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_name  VARCHAR(50)   NOT NULL UNIQUE,      -- no two departments share a name
    location   VARCHAR(50),                         -- nullable: location may be unknown
    budget     NUMERIC(12,2) CHECK (budget >= 0)    -- NUMERIC, not FLOAT: money must be exact
);

-- -----------------------------------------------------------------------------
-- employees: staff. manager_id points back into the same table (self-reference)
-- which builds an org-chart hierarchy -> used for self joins & recursive CTEs.
-- -----------------------------------------------------------------------------
CREATE TABLE employees (
    emp_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(50)   NOT NULL,
    last_name   VARCHAR(50)   NOT NULL,
    email       VARCHAR(100)  NOT NULL UNIQUE,
    dept_id     INT REFERENCES departments(dept_id),   -- NULL = CEO / contractor (no dept)
    manager_id  INT REFERENCES employees(emp_id),      -- NULL = top of the hierarchy
    job_title   VARCHAR(60)   NOT NULL,
    salary      NUMERIC(10,2) NOT NULL CHECK (salary > 0),
    hire_date   DATE          NOT NULL,
    is_active   BOOLEAN       NOT NULL DEFAULT TRUE    -- soft "left the company" flag
);

-- -----------------------------------------------------------------------------
-- categories: product categories as a TREE (parent_id -> categories)
-- e.g. Electronics > Computers > Laptops
-- -----------------------------------------------------------------------------
CREATE TABLE categories (
    category_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name  VARCHAR(50) NOT NULL,
    parent_id      INT REFERENCES categories(category_id)   -- NULL = root category
);

-- -----------------------------------------------------------------------------
-- products: what the shop sells
-- -----------------------------------------------------------------------------
CREATE TABLE products (
    product_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name     VARCHAR(100)  NOT NULL,
    category_id      INT           NOT NULL REFERENCES categories(category_id),
    price            NUMERIC(10,2) NOT NULL CHECK (price >= 0),  -- current list price
    cost             NUMERIC(10,2) CHECK (cost >= 0),            -- what we pay the supplier
    stock_qty        INT           NOT NULL DEFAULT 0 CHECK (stock_qty >= 0),
    is_discontinued  BOOLEAN       NOT NULL DEFAULT FALSE,
    attributes       JSONB,        -- flexible per-product details (brand, ram_gb, author...)
    created_at       DATE          NOT NULL
);

-- -----------------------------------------------------------------------------
-- customers: people who buy. referred_by is another self-reference
-- (customer A referred customer B) -> referral chains.
-- -----------------------------------------------------------------------------
CREATE TABLE customers (
    customer_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   VARCHAR(50)  NOT NULL,
    last_name    VARCHAR(50)  NOT NULL,
    email        VARCHAR(100) NOT NULL UNIQUE,
    phone        VARCHAR(20),               -- optional -> contains NULLs on purpose
    city         VARCHAR(50),               -- optional -> one NULL on purpose
    country      VARCHAR(50)  NOT NULL,
    signup_date  DATE         NOT NULL,
    referred_by  INT REFERENCES customers(customer_id)
);

-- -----------------------------------------------------------------------------
-- orders: one row per order (the "header")
-- -----------------------------------------------------------------------------
CREATE TABLE orders (
    order_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INT       NOT NULL REFERENCES customers(customer_id),
    employee_id   INT       REFERENCES employees(emp_id),  -- sales rep; NULL = online self-checkout
    order_date    TIMESTAMP NOT NULL,                       -- TIMESTAMP: we care about time of day too
    status        VARCHAR(20) NOT NULL
                  -- CHECK with IN acts like a lightweight enum; easier to change than CREATE TYPE ... AS ENUM
                  CHECK (status IN ('pending','shipped','delivered','cancelled','returned')),
    shipped_date  DATE                                      -- NULL until shipped
);

-- -----------------------------------------------------------------------------
-- order_items: the lines of each order (many-to-many between orders & products)
-- -----------------------------------------------------------------------------
CREATE TABLE order_items (
    -- ON DELETE CASCADE: deleting an order deletes its lines automatically
    -- (lines have no meaning without their order).
    order_id    INT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id  INT NOT NULL REFERENCES products(product_id),
    quantity    INT NOT NULL CHECK (quantity > 0),
    -- unit_price is COPIED from products.price at purchase time. Prices change;
    -- history must not. This is deliberate denormalization.
    unit_price  NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    discount    NUMERIC(4,2)  NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 1),  -- 0.10 = 10% off
    -- Composite primary key: the same product appears at most once per order.
    PRIMARY KEY (order_id, product_id)
);

-- -----------------------------------------------------------------------------
-- payments: an order may be paid in several parts (or not at all yet)
-- -----------------------------------------------------------------------------
CREATE TABLE payments (
    payment_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    INT           NOT NULL REFERENCES orders(order_id),
    amount      NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    method      VARCHAR(20)   NOT NULL
                CHECK (method IN ('card','upi','paypal','bank_transfer','cash')),
    paid_at     TIMESTAMP     NOT NULL
);

-- -----------------------------------------------------------------------------
-- logins: customer website/app logins -> streaks, sessions, gaps & islands
-- -----------------------------------------------------------------------------
CREATE TABLE logins (
    login_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  INT         NOT NULL REFERENCES customers(customer_id),
    login_at     TIMESTAMP   NOT NULL,
    device       VARCHAR(10) NOT NULL CHECK (device IN ('web','ios','android'))
);

-- Postgres does NOT automatically index foreign-key columns (MySQL/InnoDB does).
-- We index the ones we join on most. Indexes are covered in 02_medium/09.
CREATE INDEX idx_orders_customer     ON orders(customer_id);
CREATE INDEX idx_order_items_product ON order_items(product_id);
CREATE INDEX idx_payments_order      ON payments(order_id);
CREATE INDEX idx_employees_dept      ON employees(dept_id);
